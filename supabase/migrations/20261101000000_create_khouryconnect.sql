-- PostgreSQL 17+. No dependency on Supabase's auth schema yet.
-- The application tables mirror the 11-table Airtable base.
-- Password placeholders and Airtable reverse-link columns are intentionally omitted.

create schema if not exists app_private;
revoke all on schema app_private from public;

create table public.users (
  user_id uuid primary key default gen_random_uuid(),
  email text not null check (btrim(email) <> ''),
  first_name text,
  last_name text,
  year text,
  major text,
  minor text,
  display_name text,
  bio text,
  avatar_url text,
  comments_schema_note text
);
create unique index users_email_unique on public.users (lower(email));

create table public.communities (
  community_id bigint generated by default as identity primary key,
  course_code text not null check (btrim(course_code) <> ''),
  course_name text not null check (btrim(course_name) <> ''),
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  description text,
  created_at timestamptz not null default now()
);
create unique index communities_course_code_unique
  on public.communities (upper(course_code));

create table public.professors (
  -- The source stores professor IDs as text, unlike auto-number course/post IDs.
  prof_id text primary key check (btrim(prof_id) <> ''),
  email text,
  first_name text,
  last_name text
);
create unique index professors_email_unique on public.professors (lower(email))
  where email is not null;

create table public.posts (
  post_id bigint generated by default as identity primary key,
  author_id uuid not null references public.users(user_id) on delete restrict,
  community_id bigint not null references public.communities(community_id) on delete restrict,
  title text not null check (btrim(title) <> ''),
  content text not null check (btrim(content) <> ''),
  created_at timestamptz not null default now(),
  unique (post_id, community_id)
);
create index posts_author_idx on public.posts (author_id);
create index posts_community_created_idx on public.posts (community_id, created_at desc);

create table public.post_votes (
  vote_id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(user_id) on delete cascade,
  post_id bigint not null references public.posts(post_id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, post_id)
);
create index post_votes_post_idx on public.post_votes (post_id);

create table public.community_members (
  membership_id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(user_id) on delete cascade,
  community_id bigint not null references public.communities(community_id) on delete cascade,
  role text not null default 'member',
  joined_at timestamptz not null default now(),
  unique (user_id, community_id)
);
create index community_members_community_idx on public.community_members (community_id);

create table public.community_posts (
  community_post_id bigint generated by default as identity primary key,
  post_id bigint not null,
  community_id bigint not null,
  posted_at timestamptz not null default now(),
  removed_at timestamptz,
  unique (post_id, community_id),
  -- Preserve the source join table without allowing it to contradict posts.
  foreign key (post_id, community_id)
    references public.posts(post_id, community_id) on delete cascade on update cascade,
  check (removed_at is null or removed_at >= posted_at)
);
create index community_posts_community_idx on public.community_posts (community_id);

create table public.community_profs (
  community_prof_id bigint generated by default as identity primary key,
  community_id bigint not null references public.communities(community_id) on delete cascade,
  prof_id text not null references public.professors(prof_id) on delete cascade,
  unique (community_id, prof_id)
);
create index community_profs_prof_idx on public.community_profs (prof_id);

create table public.comments (
  comment_id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(post_id) on delete cascade,
  author_id uuid not null references public.users(user_id) on delete restrict,
  parent_comment_id bigint,
  content text not null check (btrim(content) <> ''),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (comment_id, post_id),
  check (parent_comment_id is null or parent_comment_id <> comment_id),
  -- A reply must reference a parent on the same post.
  foreign key (parent_comment_id, post_id)
    references public.comments(comment_id, post_id) on delete cascade
);
create index comments_post_created_idx on public.comments (post_id, created_at);
create index comments_author_idx on public.comments (author_id);
create index comments_parent_idx on public.comments (parent_comment_id, post_id);

create table public.course_offerings (
  offering_id bigint generated by default as identity primary key,
  community_id bigint not null references public.communities(community_id) on delete restrict,
  prof_id text not null references public.professors(prof_id) on delete restrict,
  term text not null check (btrim(term) <> ''),
  section text not null check (btrim(section) <> ''),
  unique (community_id, term, section)
);
create index course_offerings_prof_idx on public.course_offerings (prof_id);

create table public.enrollments (
  enrollment_id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(user_id) on delete cascade,
  offering_id bigint not null references public.course_offerings(offering_id) on delete cascade,
  unique (user_id, offering_id)
);
create index enrollments_offering_idx on public.enrollments (offering_id);

create function app_private.touch_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at := clock_timestamp();
  return new;
end;
$$;
create trigger post_votes_touch_updated_at before update on public.post_votes
  for each row execute function app_private.touch_updated_at();
create trigger comments_touch_updated_at before update on public.comments
  for each row execute function app_private.touch_updated_at();

-- Parents must already exist (immediate FK), and thread links cannot change
-- after insertion. Together with the self-reference check, this prevents cycles.
create function app_private.keep_comment_thread()
returns trigger language plpgsql set search_path = '' as $$
begin
  if new.parent_comment_id is distinct from old.parent_comment_id
     or new.post_id is distinct from old.post_id then
    raise exception 'A comment cannot be moved to a different parent or post'
      using errcode = '23514';
  end if;
  return new;
end;
$$;
create trigger comments_keep_thread before update of parent_comment_id, post_id
  on public.comments for each row execute function app_private.keep_comment_thread();

